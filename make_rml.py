#!/usr/bin/env python3
"""Writes avalanche.rml: Avalanche Air's Rive side (docs/RIVE.md).

SKELETON (the UI's owner grows it: overlays, HUD, state machines, fonts).
Today it declares:

- GameData: the Scene3D's `data` view model, one property per pin of
  tools/pins.py (the world's bindings resolve against it);
- Game: the Scene3D's view model (scene, source, playing, ...) with `data`;
- Main: the root artboard, the Scene3D filling it, holding the keys' focus.

Ids are client 41 ("41:<n>"); the hedra_engine library's are 93.

    python3 make_rml.py           # write avalanche.rml
    python3 make_rml.py --check   # exit 1 when it would change
"""
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from pins import PINS  # noqa: E402

CLIENT = 41


class Ids:
    def __init__(self):
        self.n = 0

    def __call__(self):
        self.n += 1
        return f"{CLIENT}:{self.n}"


# Defaults for the inbound settings (the world reads them on its first frame).
DEFAULTS = {
    "musicVolume": 0.8,
    "sfxVolume": 0.9,
    "voiceVolume": 1.0,
    "landingAssist": True,
    "seed": 1,
    "countdown": -1,
    "captionLine": -1,
    "resGrade": -1,
}


def build():
    nid = Ids()
    out = ['<Rive version="1" kind="fragment">',
           "    <!-- Generated by make_rml.py: do not edit (docs/RIVE.md). -->"]
    w = out.append

    # GameData
    gd, gd_inst = nid(), nid()
    props = []
    w(f'    <ViewModel defaultInstanceId="{gd_inst}" name="GameData" id="{gd}">')
    for name, kind, _, _ in PINS:
        pid = nid()
        props.append((pid, name, kind))
        tag = "ViewModelPropertyNumber" if kind == "number" else "ViewModelPropertyBoolean"
        w(f'        <{tag} name="{name}" id="{pid}"/>')
    w(f'        <ViewModelInstance exports="true" name="Default" id="{gd_inst}">')
    for pid, name, kind in props:
        if kind == "number":
            v = DEFAULTS.get(name, 0)
            w(f'            <ViewModelInstanceNumber propertyValue="{v}" viewModelPropertyId="{pid}"/>')
        else:
            v = "true" if DEFAULTS.get(name, False) else "false"
            w(f'            <ViewModelInstanceBoolean propertyValue="{v}" viewModelPropertyId="{pid}"/>')
    w("        </ViewModelInstance>")
    w("    </ViewModel>")

    # Game: the Scene3D's view model
    g, g_inst = nid(), nid()
    p_scene, p_source, p_label, p_playing, p_speed, p_status, p_data = (nid() for _ in range(7))
    w(f'    <ViewModel defaultInstanceId="{g_inst}" name="Game" id="{g}">')
    w(f'        <ViewModelPropertyString name="scene" id="{p_scene}"/>')
    w(f'        <ViewModelPropertyString name="source" id="{p_source}"/>')
    w(f'        <ViewModelPropertyBoolean name="unbuiltLabel" id="{p_label}"/>')
    w(f'        <ViewModelPropertyBoolean name="playing" id="{p_playing}"/>')
    w(f'        <ViewModelPropertyNumber name="speed" id="{p_speed}"/>')
    w(f'        <ViewModelPropertyString name="status" id="{p_status}"/>')
    w(f'        <ViewModelPropertyViewModel viewModelReferenceId="{gd}" name="data" id="{p_data}"/>')
    w(f'        <ViewModelInstance exports="true" name="Default" id="{g_inst}">')
    w(f'            <ViewModelInstanceString propertyValue="world/run.rscn" viewModelPropertyId="{p_scene}"/>')
    w(f'            <ViewModelInstanceString propertyValue="auto" viewModelPropertyId="{p_source}"/>')
    w(f'            <ViewModelInstanceBoolean propertyValue="false" viewModelPropertyId="{p_label}"/>')
    w(f'            <ViewModelInstanceBoolean propertyValue="true" viewModelPropertyId="{p_playing}"/>')
    w(f'            <ViewModelInstanceNumber propertyValue="1" viewModelPropertyId="{p_speed}"/>')
    w(f'            <ViewModelInstanceString propertyValue="" viewModelPropertyId="{p_status}"/>')
    w(f'            <ViewModelInstanceViewModel propertyValue="{gd_inst}" viewModelPropertyId="{p_data}"/>')
    w("        </ViewModelInstance>")
    w("    </ViewModel>")

    # Main
    ab, ab_style, root, root_style, layout, sm, layer, state = (nid() for _ in range(8))
    w(f'    <Artboard defaultStateMachineId="{sm}" viewModelId="{g}" viewModelInstanceId="{g_inst}" clip="true" '
      f'x="0" y="0" width="960" height="720" styleId="{ab_style}" name="Main" id="{ab}">')
    w(f'        <LayoutComponentStyle name="Artboard Style" id="{ab_style}"/>')
    w(f'        <LayoutComponent width="960" height="720" styleId="{root_style}" name="Root Layout" id="{root}">')
    w(f'            <LayoutComponentStyle layoutWidthScaleType="1" layoutHeightScaleType="1" widthUnitsValue="3" '
      f'heightUnitsValue="3" name="Layout Style" id="{root_style}"/>')
    w(f'            <ScriptedLayout scriptAssetId="93:1" name="Scene3D" id="{layout}">')
    w('                <FocusData canTraverse="false" name="Keys"/>')
    w("            </ScriptedLayout>")
    w("        </LayoutComponent>")
    w("        <!-- binds the view model: rive binds an artboard's view model only through its state machine -->")
    w(f'        <StateMachine name="Main" id="{sm}">')
    w(f'            <StateMachineLayer name="Layer" id="{layer}">')
    w('                <AnyState x="200" y="-120"/>')
    w('                <ExitState x="400" y="-120"/>')
    w("                <EntryState>")
    w(f'                    <StateTransition stateToId="{state}"/>')
    w("                </EntryState>")
    w(f'                <AnimationState x="160" y="0" id="{state}"/>')
    w("            </StateMachineLayer>")
    w("        </StateMachine>")
    w("    </Artboard>")
    w("</Rive>")
    return "\n".join(out) + "\n"


def main():
    path = os.path.join(ROOT, "avalanche.rml")
    text = build()
    old = open(path).read() if os.path.exists(path) else None
    if "--check" in sys.argv:
        sys.exit(0 if old == text else 1)
    if old != text:
        with open(path, "w") as f:
            f.write(text)
        print("wrote avalanche.rml")


if __name__ == "__main__":
    main()
