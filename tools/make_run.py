#!/usr/bin/env python3
"""Writes world/run.rscn and world/scripts/pins_data.as.

run.rscn is the run's scene: psx-style's frame rig (docs/LOOK.md, section 1)
with, under its LowRes SubViewport, the course (course/course.rscn, the
course's owner's), the rider (rider/rider.rscn, the gameplay's), the sound
node (scripts/sound.as, the audio's) and the lens (scripts/camera.as drives
it); on its root the driver (scripts/run.as) and the Pins (tools/pins.py).
Nobody edits run.rscn by hand: change this script or the sub-scenes.

    python3 tools/make_run.py           # write
    python3 tools/make_run.py --check   # exit 1 when a file would change
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pins import PINS  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORLD = os.path.join(ROOT, "world")


def cap(name):
    return name[0].upper() + name[1:]


def run_rscn():
    out = []
    w = out.append
    w('<?xml version="1.0" encoding="UTF-8"?>')
    w("<!-- Generated by tools/make_run.py: do not edit. The run's scene: the PSX")
    w("     frame rig (docs/LOOK.md, section 1) with the course, the rider, the sound")
    w("     and the lens under LowRes; the driver and the pins on the root. -->")
    w('<rscn format="2">')
    w('  <ext_resource id="1_present" type="Shader" path="res://psx/psx_present.wgsl"/>')
    w('  <ext_resource id="3_run" type="Script" path="res://scripts/run.as"/>')
    w('  <ext_resource id="4_sound" type="Script" path="res://scripts/sound.as"/>')
    w('  <ext_resource id="5_camera" type="Script" path="res://scripts/camera.as"/>')
    w('  <ext_resource id="6_course" type="PackedScene" path="res://course/course.rscn"/>')
    w('  <ext_resource id="7_rider" type="PackedScene" path="res://rider/rider.rscn"/>')
    w("")
    w("  <!-- the view model the scene's bindings use: the Scene3D's `data`, GameData")
    w("       (make_rml.py declares it from tools/pins.py) -->")
    w('  <sub_resource id="VM_game" type="ViewModel">')
    w('    <property name="view_model">"GameData"</property>')
    w("  </sub_resource>")
    w('  <sub_resource id="Env_frame" type="Environment">')
    w('    <property name="background_mode">1</property>')
    w('    <property name="background_color">Color(0, 0, 0, 1)</property>')
    w('    <property name="tonemap_mode">0</property>')
    w("  </sub_resource>")
    w('  <sub_resource id="Tex_low" type="ViewportTexture">')
    w('    <property name="viewport_path">NodePath("LowRes")</property>')
    w("  </sub_resource>")
    w('  <sub_resource id="Mat_present" type="ShaderMaterial">')
    w('    <property name="shader">ExtResource("1_present")</property>')
    w('    <property name="shader_parameter/screen">SubResource("Tex_low")</property>')
    w('    <property name="shader_parameter/low_res">Vector2(320, 240)</property>')
    w("  </sub_resource>")
    w('  <sub_resource id="Mesh_present" type="QuadMesh">')
    w('    <property name="material">SubResource("Mat_present")</property>')
    w("  </sub_resource>")
    w("  <!-- gap E-VPTEX: a standard slot names the viewport texture so its target is made -->")
    w('  <sub_resource id="Mat_anchor" type="StandardMaterial3D">')
    w('    <property name="shading_mode">0</property>')
    w('    <property name="albedo_texture">SubResource("Tex_low")</property>')
    w("  </sub_resource>")
    w('  <sub_resource id="Mesh_anchor" type="QuadMesh">')
    w('    <property name="size">Vector2(0.001, 0.001)</property>')
    w('    <property name="material">SubResource("Mat_anchor")</property>')
    w("  </sub_resource>")
    w("")
    w('  <node name="Run" type="Node3D">')
    w('    <property name="script">ExtResource("3_run")</property>')
    w('    <property name="view_model">SubResource("VM_game")</property>')
    w("  </node>")
    w('  <node name="FrameEnvironment" type="WorldEnvironment" parent=".">')
    w('    <property name="environment">SubResource("Env_frame")</property>')
    w("  </node>")
    w('  <node name="Screen" type="Camera3D" parent=".">')
    w('    <property name="current">true</property>')
    w("  </node>")
    w('  <node name="Present" type="MeshInstance3D" parent="Screen">')
    w('    <property name="mesh">SubResource("Mesh_present")</property>')
    w('    <property name="position">Vector3(0, 0, -1)</property>')
    w("  </node>")
    w('  <node name="Anchor" type="MeshInstance3D" parent="Screen">')
    w('    <property name="mesh">SubResource("Mesh_anchor")</property>')
    w('    <property name="position">Vector3(0, 0, -2)</property>')
    w("  </node>")
    w('  <node name="LowRes" type="SubViewport" parent=".">')
    w('    <property name="size">Vector2i(320, 240)</property>')
    w('    <property name="render_target_update_mode">4</property>')
    w('    <property name="own_world_3d">true</property>')
    w("  </node>")
    w("  <!-- the course brings the game world's Environment (depth fog), its sky and the")
    w("       Daylight timeline that course/course.rscn's script scrubs along the progress -->")
    w('  <node name="Course" parent="LowRes" instance="ExtResource(&quot;6_course&quot;)"/>')
    w('  <node name="Rider" parent="LowRes" instance="ExtResource(&quot;7_rider&quot;)"/>')
    w("  <!-- the rider's screen anchor for the HUD's pop-ups: scripts/run.as keeps it")
    w("       1.2 m over the rider; its outputs are bound, no pin needed -->")
    w('  <node name="RiderAnchor" type="Node3D" parent="LowRes">')
    w('    <binding property="screen_position:x" path="riderX" mode="to_source"/>')
    w('    <binding property="screen_position:y" path="riderY" mode="to_source"/>')
    w("  </node>")
    w('  <node name="Lens" type="Camera3D" parent="LowRes">')
    w('    <property name="script">ExtResource("5_camera")</property>')
    w('    <property name="position">Vector3(0, 2.5, 5)</property>')
    w('    <property name="rotation_degrees">Vector3(-12, 0, 0)</property>')
    w('    <property name="fov">66</property>')
    w('    <property name="near">0.1</property>')
    w('    <property name="far">500</property>')
    w('    <property name="current">true</property>')
    w("  </node>")
    w('  <node name="Sound" type="Node" parent=".">')
    w('    <property name="script">ExtResource("4_sound")</property>')
    w("  </node>")
    w("  <!-- the pins (tools/pins.py, docs/RIVE.md section 4) -->")
    w('  <node name="Pins" type="Node3D" parent=".">')
    w('    <property name="visible">false</property>')
    w("  </node>")
    w('  <node name="In" type="Node3D" parent="Pins"/>')
    for name, kind, direction, _ in PINS:
        if direction == "output":
            continue
        parent = "Pins" if direction == "out" else "Pins/In"
        prop = "position:x" if kind == "number" else "visible"
        mode = ' mode="to_source"' if direction == "out" else ""
        w(f'  <node name="{cap(name)}" type="Node3D" parent="{parent}">')
        w(f'    <binding property="{prop}" path="{name}"{mode}/>')
        w("  </node>")
    w("</rscn>")
    return "\n".join(out) + "\n"


def pins_data():
    out = ["// Generated by tools/make_run.py from tools/pins.py: do not edit.",
           "// Each pin's node path from the run scene's root, and its index in PIN_PATHS.",
           "// Numbers ride the node's position.x, booleans its visible (docs/RIVE.md, section 4).", ""]
    paths = []
    rows = [p for p in PINS if p[2] != "output"]
    for i, (name, kind, direction, meaning) in enumerate(rows):
        parent = "Pins" if direction == "out" else "Pins/In"
        paths.append(f"{parent}/{cap(name)}")
        const = "PIN_" + "".join("_" + c if c.isupper() else c.upper() for c in name).lstrip("_")
        out.append(f"export const {const}: i32 = {i};  // {kind} {direction}: {meaning}")
    out.append("")
    out.append(f"export const PIN_COUNT: i32 = {len(rows)};")
    out.append("export const PIN_PATHS: StaticArray<string> = [")
    out.extend(f'    "{p}",' for p in paths)
    out.append("];")
    out.append("// true for a boolean pin (its visible), false for a number (its position.x)")
    out.append("export const PIN_IS_BOOL: StaticArray<bool> = [")
    out.extend(f"    {'true' if k == 'bool' else 'false'}," for _, k, _, _ in rows)
    out.append("];")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv
    files = {
        os.path.join(WORLD, "run.rscn"): run_rscn(),
        os.path.join(WORLD, "scripts", "pins_data.as"): pins_data(),
    }
    changed = []
    for path, text in files.items():
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            changed.append(path)
            if not check:
                with open(path, "w") as f:
                    f.write(text)
    for p in changed:
        print(("would change " if check else "wrote ") + os.path.relpath(p, ROOT))
    sys.exit(1 if check and changed else 0)


if __name__ == "__main__":
    main()
