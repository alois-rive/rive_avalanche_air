"""world/scripts/course_data.as: what course_api.as reads (docs/COURSE.md,
section 10), written from the built course."""
import math

import course as C
from build import BLK, G
from meshes import num


def arr(name, kind, values, fmt, per_line=16, comment=None):
    out = []
    if comment:
        out.append("// " + comment)
    out.append("export const %s: StaticArray<%s> = [" % (name, kind))
    for i in range(0, len(values), per_line):
        out.append("    " + ", ".join(fmt(v) for v in values[i:i + per_line]) + ",")
    out.append("];")
    return out


def ff(v):
    s = num(v, 3)
    return s if ("." in s or "e" in s) else s + ".0"


def fi(v):
    return str(int(v))


def module(data, trees):
    g = data.grid
    L = []
    w = L.append
    w("// Generated by tools/course/make_course.py from tools/course/course.py: do not edit.")
    w("// The course's data for course_api.as (docs/COURSE.md, section 10). Frame: metres,")
    w("// Y up, the line from the origin down -Z, +X right going down.")
    w("")
    w("export const COURSE_LENGTH_DATA: f32 = %s;" % ff(C.COURSE_LENGTH))
    w("export const FINISH_S_DATA: f32 = %s;" % ff(C.FINISH_S))
    w("export const SPLIT_S_DATA: f32 = %s;" % ff(C.SPLIT_S))
    w("export const MERGE_S_DATA: f32 = %s;" % ff(C.MERGE_S))
    w("export const MEGA_LIP_S_DATA: f32 = %s;" % ff(C.MEGA_LIP_S))
    w("export const HIGH_LENGTH_DATA: f32 = %s;" % ff(C.HIGH_LENGTH))
    w("")
    # ---- the ground grid
    w("// ---- the ground grid: rows every GRID_STEP m down from GRID_Z0, columns from GRID_X0;")
    w("// row r holds columns ROW_C0[r] .. ROW_C0[r] + ROW_N[r] - 1, its heights at")
    w("// ROW_OFF[r] in GRID_H (cm above ROW_Y[r]); each cell split from (r, c) to (r+1, c+1)")
    w("export const GRID_STEP: f32 = %s;" % ff(G))
    w("export const GRID_X0: f32 = %s;" % ff(g.X0))
    w("export const GRID_Z0: f32 = %s;" % ff(g.Z0))
    w("export const GRID_ROWS: i32 = %d;" % g.rows)
    c0 = []
    nn = []
    off = []
    hs = []
    for r in range(g.rows):
        c0.append(g.c0[r])
        nn.append(g.c1[r] - g.c0[r] + 1)
        off.append(len(hs))
        ref = g.row_y[r]
        for v in g.h[r]:
            q = int(round((v - ref) * 100))
            if not -32768 <= q <= 32767:
                raise ValueError("grid height out of range at row %d" % r)
            hs.append(q)
    L += arr("ROW_C0", "i32", c0, fi, 24)
    L += arr("ROW_N", "i32", nn, fi, 24)
    L += arr("ROW_OFF", "i32", off, fi, 16)
    L += arr("ROW_Y", "f32", g.row_y, lambda v: ff(v), 12)
    L += arr("GRID_H", "i16", hs, fi, 32)
    # ---- the pistes per row
    pv = []
    for iv in data.piste:
        for a, b in iv:
            pv += [a, b]
    L += arr("PISTE", "f32", pv, ff, 16, "each row's two piste intervals (x from, x to; empty when from > to)")
    w("")
    # ---- the lines
    for name, smp in (("LINE", data.main_samples), ("HIGH", data.high_samples)):
        w("export const %s_N: i32 = %d;" % (name, len(smp)))
        p = []
        t = []
        wd = []
        fl = []
        ss = []
        for sm in smp:
            p += [sm["x"], sm["y"], sm["z"]]
            t += list(sm["t"])
            wd.append(sm["width"])
            fl.append(sm["section"] | (8 if sm["safe"] else 0) | (sm["surface"] << 4) | (128 if sm["air"] else 0))
            ss.append(sm["s"])
        L += arr(name + "_P", "f32", p, ff, 12, "x, y, z of each sample (1 m of s apart)")
        L += arr(name + "_T", "f32", t, lambda v: num(v, 4) if "." in num(v, 4) else num(v, 4) + ".0", 12,
                 "the unit tangent downhill")
        L += arr(name + "_W", "f32", wd, ff, 16)
        L += arr(name + "_F", "i32", fl, fi, 24, "section | 8 safe | surface << 4 | 128 in the air")
        if name == "HIGH":
            L += arr(name + "_S", "f32", ss, ff, 16, "the main line's s of each sample")
        w("")
    # ---- rails
    rails = data.rails
    w("export const RAIL_N: i32 = %d;" % len(rails))
    L += arr("RAIL_KIND", "i32", [r["kind"] for r in rails], fi)
    L += arr("RAIL_FLAGS", "i32", [r["flags"] for r in rails], fi)
    starts = []
    pts = []
    box = []
    for r in rails:
        starts.append(len(pts) // 3)
        xs = [p[0] for p in r["pts"]]
        zs = [p[2] for p in r["pts"]]
        box += [min(xs), max(xs), min(zs), max(zs)]
        for p in r["pts"]:
            pts += list(p)
    L += arr("RAIL_START", "i32", starts, fi)
    L += arr("RAIL_COUNT", "i32", [len(r["pts"]) for r in rails], fi)
    L += arr("RAIL_S0", "f32", [r["s"] for r in rails], ff)
    L += arr("RAIL_AABB", "f32", box, ff, 16, "x min, x max, z min, z max")
    L += arr("RAIL_PTS", "f32", pts, ff, 12, "the top every 0.25 m")
    w("")
    # ---- features
    fs = data.features
    w("export const FEAT_N: i32 = %d;" % len(fs))
    L += arr("FEAT_KIND", "i32", [f["kind"] for f in fs], fi)
    L += arr("FEAT_S", "f32", [f["s"] for f in fs], ff)
    L += arr("FEAT_X", "f32", [f["x"] for f in fs], ff)
    # (u8, not bool: the pinned compiler reads every element of a bool
    # array literal after the first as false; rive_modeler's check_repo
    # "bools", cli/program/ENGINEERING.md pitfall 20)
    L += arr("FEAT_HIGH", "u8", [f["high"] for f in fs], lambda v: "1" if v else "0")
    L += arr("FEAT_LIPH", "f32", [f["lip_h"] for f in fs], ff)
    L += arr("FEAT_LIPA", "f32", [f["lip_a"] for f in fs], ff)
    L += arr("FEAT_V", "f32", [f["v"] for f in fs], ff)
    L += arr("FEAT_AIR", "f32", [f["air"] for f in fs], ff)
    L += arr("FEAT_RAILI", "i32", [f["rail"] for f in fs], fi)
    w("// the features' footprints for ground(): the feature, its frame (origin x, z,")
    w("// forward x, z), u from, u to, half width, lip from, lip to (u); FOOT_MASK: per")
    w("// block row (4 grid rows) the footprints that touch it, a bit each")
    foot = []
    fidx = []
    for i, f in enumerate(fs):
        o = f["overlay"]
        if o is None:
            continue
        ox, oz, fx, fz, rx, rz = o.frame
        lip = o.lip if (o.lip and f["kind"] in (2, 4, 6)) else (1.0, 0.0)
        fidx.append(i)
        foot += [ox, oz, fx, fz, o.u0, o.u1, o.half_w + 0.75, lip[0], lip[1]]
        f["foot"] = len(fidx) - 1
    if len(fidx) > 32:
        raise ValueError("more than 32 terrain features: FOOT_MASK holds 32")
    w("export const FOOT_N: i32 = %d;" % len(fidx))
    L += arr("FOOT_FEAT", "i32", fidx, fi)
    L += arr("FOOT", "f32", foot, ff, 9)
    masks = [0] * g.brows
    for k, i in enumerate(fidx):
        o = fs[i]["overlay"]
        x0, x1, z0, z1 = o.bbox()
        b0 = max(0, int(math.floor((g.Z0 - z1) / BLK)))
        b1 = min(g.brows - 1, int(math.floor((g.Z0 - z0) / BLK)))
        for b in range(b0, b1 + 1):
            masks[b] |= 1 << k
    L += arr("FOOT_MASK", "u32", masks, fi, 16)
    rf = data.feats.roof
    ox, oz, fx, fz, rx, rz = rf["frame"]
    hg = next(i for i, f in enumerate(fs) if f["id"] == "HG")
    L += arr("ROOF", "f32", [ox, oz, fx, fz, rf["u0"], rf["u1"], rf["half_w"], rf["top"]], ff, 8,
             "the station's roof (HG): frame, u from, u to, half width, top")
    w("export const ROOF_FEAT: i32 = %d;" % hg)
    w("")
    # ---- the lake
    lx, lz, lfx, lfz, lrx, lrz = g.lake_frame
    a, b = g.lake_ab
    L += arr("LAKE", "f32", [lx, lz, lfx, lfz, a, b], ff, 6, "the frozen lake: frame, half length, half width")
    # ---- fall zones
    fz_ = data.fall
    w("export const FALL_N: i32 = %d;" % len(fz_))
    fv = []
    for z_ in fz_:
        fv += list(z_["frame"]) + [z_["u0"], z_["u1"], z_["ytop"]]
    L += arr("FALL", "f32", fv, ff, 7, "frame (x, z, forward x, z), u from, u to, top")
    w("")
    # ---- obstacles
    obs = trees.obstacles
    w("export const OBS_N: i32 = %d;" % len(obs))
    ov = []
    for o in obs:
        ov += [o["x"], o["z"], o["r"], o["bottom"], o["top"]]
    L += arr("OBS", "f32", ov, ff, 15, "x, z, radius, bottom, top (sorted by z, down the course)")
    L += arr("OBS_ROCK", "u8", [o.get("rock", False) for o in obs], lambda v: "1" if v else "0", 24)
    starts = []
    k = 0
    for b in range(g.brows + 1):
        zb = g.Z0 - b * BLK
        while k < len(obs) and obs[k]["z"] > zb:
            k += 1
        starts.append(k)
    L += arr("OBS_BLOCK", "i32", starts, fi, 24, "the first obstacle at or below each block row's top")
    w("")
    # ---- the sun
    sun = data.sun
    w("export const SUN_N: i32 = %d;" % len(sun))
    L += arr("SUN_S", "f32", [k_["s"] for k_ in sun], ff)
    sv = []
    for k_ in sun:
        sv += list(k_["dir"]) + list(k_["sun"]) + list(k_["zenith"]) + list(k_["horizon"]) + \
            list(k_["sky_amb"]) + list(k_["ground_amb"]) + [k_["fog_begin"], k_["fog_end"]]
    L += arr("SUN_K", "f32", sv, lambda v: num(v, 4) if "." in num(v, 4) else num(v, 4) + ".0", 20,
             "per key: direction xyz, sun rgb, zenith rgb, horizon rgb, sky ambient rgb, snow bounce rgb, fog begin, fog end")
    return "\n".join(L) + "\n"
